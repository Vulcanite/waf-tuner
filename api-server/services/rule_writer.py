"""
Rule Writer — Phase 5

Writes approved exception rules to the ModSecurity exceptions directory
and triggers nginx reload via the Docker SDK.
"""
import logging
import os
from datetime import datetime, timezone

logger = logging.getLogger(__name__)

MODSEC_EXCEPTIONS_DIR = os.environ.get("MODSEC_EXCEPTIONS_DIR", "/app/data/exceptions/")
NGINX_CONTAINER_NAME = os.environ.get("NGINX_CONTAINER_NAME", "nginx")


def _exception_filename(draft_id: int, uri: str) -> str:
    safe_uri = uri.replace("/", "_").strip("_") or "root"
    return f"exception_{draft_id}_{safe_uri}.conf"


def write_exception(draft) -> None:
    """Write the proposed_rule for a draft to the exceptions directory."""
    os.makedirs(MODSEC_EXCEPTIONS_DIR, exist_ok=True)

    scope = draft.proposed_rule_scope or {}
    uri = scope.get("uri", "/")
    rule_id = scope.get("rule_id", "unknown")

    filename = _exception_filename(draft.id, uri)
    filepath = os.path.join(MODSEC_EXCEPTIONS_DIR, filename)

    with open(filepath, "w") as f:
        f.write(f"# Exception {draft.id} — generated by WAF agent\n")
        f.write(f"# Rule: {rule_id}\n")
        f.write(f"# URI: {uri}\n")
        f.write(f"# Deployed: {datetime.now(timezone.utc).isoformat()}\n\n")
        f.write((draft.proposed_rule or "") + "\n")

    logger.info("Wrote exception file: %s", filepath)


def _run_nginx_command(args: list[str]) -> tuple[int, str]:
    """
    Run Nginx command. Supports both docker container execution (default)
    and local system command execution (if USE_LOCAL_NGINX is True or Docker is unavailable).
    """
    use_local = os.environ.get("USE_LOCAL_NGINX", "false").lower() in ("true", "1", "yes")

    if not use_local:
        try:
            import docker
            client = docker.from_env()
            container = client.containers.get(
                os.environ.get("NGINX_CONTAINER_NAME", NGINX_CONTAINER_NAME)
            )
            cmd = " ".join(args)
            result = container.exec_run(cmd)
            return result.exit_code, result.output.decode("utf-8", errors="replace")
        except Exception as e:
            logger.info("Docker Nginx command failed (%s). Falling back to local command...", e)
            use_local = True

    if use_local:
        try:
            import subprocess
            result = subprocess.run(args, capture_output=True, text=True)
            output = (result.stdout or "") + "\n" + (result.stderr or "")
            return result.returncode, output
        except Exception as e:
            logger.error("Local Nginx command failed: %s", e)
            return 1, str(e)


def validate_exception(draft) -> bool:
    """Write the .conf file and run nginx -t to validate. Delete on failure."""
    write_exception(draft)
    try:
        exit_code, output = _run_nginx_command(["nginx", "-t"])
        if exit_code != 0:
            logger.warning(
                "nginx -t failed for exception %d: %s",
                draft.id,
                output,
            )
            delete_exception(draft)
            return False
        return True
    except Exception as e:
        logger.error("validate_exception failed: %s", e)
        delete_exception(draft)
        return False


def reload_nginx() -> bool:
    """
    Run nginx -t then nginx -s reload. Supports Docker container reload
    or local system reload. Returns True on success.
    """
    try:
        # Config test first
        test_code, test_output = _run_nginx_command(["nginx", "-t"])
        if test_code != 0:
            logger.error("nginx -t failed before reload: %s", test_output)
            return False

        # Trigger reload
        reload_code, reload_output = _run_nginx_command(["nginx", "-s", "reload"])
        if reload_code == 0:
            logger.info("nginx reloaded successfully")
            return True
        else:
            logger.error("nginx reload failed: %s", reload_output)
            return False

    except Exception as e:
        logger.error("reload_nginx failed: %s", e)
        return False


def delete_exception(draft) -> None:
    """Remove the exception .conf file for a draft."""
    scope = draft.proposed_rule_scope or {}
    uri = scope.get("uri", "/")
    filename = _exception_filename(draft.id, uri)
    filepath = os.path.join(MODSEC_EXCEPTIONS_DIR, filename)
    if os.path.exists(filepath):
        os.remove(filepath)
        logger.info("Deleted exception file: %s", filepath)
